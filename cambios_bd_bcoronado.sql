CREATE TABLE SGI.TIPO_INTERVENCION (
	ID_TIPO_INTERVENCION INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL,
	NOMBRE VARCHAR2(255) NOT NULL,
	ID_DEPTO INTEGER NOT NULL,
	ESTADO INTEGER DEFAULT 0 NOT NULL,
	CONSTRAINT TIPO_INTERVENCION_PK PRIMARY KEY (ID_TIPO_INTERVENCION),
	CONSTRAINT TIPO_INTERVENCION_DEPTOS_FK FOREIGN KEY (ID_DEPTO) REFERENCES SGI.DEPTOS(ID)
);